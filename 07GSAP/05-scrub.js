const timeline = gsap.timeline();
const ani = timeline
  .to(".section2 .box", {
    x: 100,
  })
  .to(".section2 .box", {
    y: -100,
  })
  .to(".section2 .box", {
    x: 200,
  })
  .to(".section2 .box", {
    y: 0,
  });

ScrollTrigger.create({
  trigger: ".section2",
  start: "top center",
  end: "500 center",
  animation: ani,
  markers: true,
  // scrub: true,
  scrub: 1, //boolean 값 대신 숫자를 주면 탄성을 줄 수 있다.
});
